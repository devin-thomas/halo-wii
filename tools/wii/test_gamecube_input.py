"""HWI-039: the GameCube pad as the player's controller (port/wii/engine/wii_xinput.c).

The host check (gamecube_input_check.c) runs the Wii's XInput, compiled whole, under the engine's own gamepad
read taken verbatim from source/input/input_xbox.c (generated here into engine_input_extract.h): every one of
the profile's game controls from its GameCube input, the triggers' presses, held counts across frame rates,
the sticks' dead zone, the layers' switch and unplugging. The static checks tie the rest of the chain: the
game controls to player_control's buttons and the unit's control bits, the look inversion, and where the
layer's signal comes from.
"""
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INPUT_XBOX = ROOT / "source" / "input" / "input_xbox.c"
INPUT_ABSTRACTION = ROOT / "source" / "input" / "input_abstraction.c"
CSERIES = ROOT / "source" / "cseries" / "cseries.h"
PLAYER_CONTROL = ROOT / "source" / "game" / "player_control.c"
WII_XINPUT = ROOT / "port" / "wii" / "engine" / "wii_xinput.c"
UNSUPPORTED_PORT = ROOT / "port" / "wii" / "engine" / "unsupported_port.c"

GAME_CONTROLS = ("jump", "switch_grenades", "action", "switch_weapons", "melee", "flashlight", "grenade",
                 "primary_trigger", "start", "back", "crouch", "zoom")


def compiler():
    for name in ("gcc", "cc", "clang"):
        path = shutil.which(name)
        if path:
            return path
    return None


def _text(path):
    return path.read_text(encoding="utf-8")


def _function(text, name):
    """a C function definition, from the line naming it to its closing brace"""
    match = re.search(r"^(?:static )?[A-Za-z_][\w \*]*\b%s\(\n[^;{]*\)\n\{" % re.escape(name), text, re.M)
    assert match, name
    index = match.end() - 1
    depth = 0
    while True:
        depth += {"{": 1, "}": -1}.get(text[index], 0)
        index += 1
        if depth == 0:
            return text[match.start():index]


def _between(text, start, end):
    first = text.index(start)
    return text[first:text.index(end, first)]


def engine_extract():
    """input_xbox.c's gamepad read and what it needs, as a header for the host check"""
    xbox = _text(INPUT_XBOX)
    cseries = _text(CSERIES)
    parts = ["/* generated by tools/wii/test_gamecube_input.py from source/input/input_xbox.c,",
             "source/input/input_abstraction.c and source/cseries/cseries.h: do not edit */", ""]
    for name in ("MIN", "CEILING", "PIN", "FLAG", "TEST_FLAG", "SET_FLAG"):
        line = re.search(r"^#define %s\(.*$" % name, cseries, re.M)
        assert line, name
        parts += ["#undef %s" % name, line.group(0)]
    constants = []
    for name in ("TICKS_PER_SECOND", "SHORT_MAX", "SHORT_MIN", "UNSIGNED_CHAR_MAX"):
        value = re.search(r"^\t%s = (.+?),?$" % name, cseries, re.M)
        assert value, name
        constants.append("\t%s = %s," % (name, value.group(1)))
    parts += ["enum", "{"] + constants + ["};", "", '#include "input/input.h"', ""]
    parts.append(_between(xbox, "/* ---------- constants */", "/* ---------- macros */"))
    parts.append(_between(xbox, "struct raw_gamepad_state\n", "struct input_globals\n"))
    parts += ["static struct",
              "{",
              "\tstruct raw_gamepad_state raw_gamepad_states[MAXIMUM_GAMEPADS];",
              "\tHANDLE gamepad_handles[MAXIMUM_GAMEPADS];",
              "\tstruct gamepad_state gamepad_states[MAXIMUM_GAMEPADS];",
              "} input_globals;", ""]
    parts.append(re.search(r"^static long gamepad_button_down_times\[.*$", xbox, re.M).group(0) + "\n")
    for table in ("gamepad_analog_button_indices", "gamepad_binary_button_masks"):
        match = re.search(r"^static const byte %s\[[^\]]*\] =\n\{.*?\};\n" % table, xbox, re.M | re.S)
        assert match, table
        parts.append(match.group(0))
    parts.append(_function(xbox, "fix_dead_zone"))
    parts.append(_function(xbox, "update_hold_ticks"))
    parts.append(_function(xbox, "input_update_analog_button_state"))

    body = _function(xbox, "input_get_device_states")
    changes = _between(body, "\t{\n\t\tunsigned long insertions;", "\tif (XGetDeviceChanges(\n\t\tXDEVICE_TYPE_MEMORY_UNIT")
    reads = body[body.index("input_abstraction_update_device_changes(device_change_flags);\n") +
                 len("input_abstraction_update_device_changes(device_change_flags);\n"):]
    parts += ["/* input_get_device_states, but for the memory units and the input abstraction's notice */",
              "static void engine_get_device_states(",
              "\tvoid)",
              "{",
              "\tunsigned long device_change_flags = 0;",
              "\tshort gamepad_index;",
              "",
              changes,
              "\t(void)device_change_flags;",
              reads, ""]

    defaults = _function(_text(INPUT_ABSTRACTION), "set_default_game_input_preferences")
    rows = re.findall(r"game_control_to_xbox_buttons\[_game_control_(\w+)\] = (_gamepad_\w+);", defaults)
    assert [name for name, _ in rows] == list(GAME_CONTROLS), rows
    parts += ["enum { NONE_BUTTON = -1 };",
              "static const struct { const char *name; short button; } default_game_controls[] =",
              "{"] + ['\t{ "%s", %s },' % row for row in rows] + ["};", ""]
    return "\n".join(parts)


@unittest.skipUnless(compiler(), "no host C compiler")
class HostCheckTests(unittest.TestCase):
    def test_pad_through_the_engines_read(self):
        with tempfile.TemporaryDirectory() as temp:
            (Path(temp) / "engine_input_extract.h").write_text(engine_extract(), encoding="utf-8")
            # (the header alone: its directory's others are the desktop port's C runtime)
            shutil.copy(ROOT / "port" / "linux" / "include" / "halo_ui_pointer.h", temp)
            exe = Path(temp) / ("gamecube_input_check.exe" if sys.platform == "win32" else "gamecube_input_check")
            build = subprocess.run(
                [compiler(), "-std=gnu11", "-O1", "-Wall", "-Wextra", "-Werror", "-Wno-unused-function",
                 "-I" + temp, "-I" + str(ROOT / "port" / "include" / "xdk"), "-I" + str(ROOT / "port" / "wii" / "engine"),
                 "-I" + str(ROOT / "source"),
                 "-o", str(exe), str(ROOT / "tools" / "wii" / "gamecube_input_check.c")],
                capture_output=True, text=True)
            self.assertEqual(build.returncode, 0, build.stderr[-6000:])
            result = subprocess.run([str(exe)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stdout[-2000:] + result.stderr[-6000:])
            match = re.search(r"^ok (\d+) checks$", result.stdout, re.M)
            self.assertIsNotNone(match, result.stdout)
            self.assertGreater(int(match.group(1)), 500)
            for control in GAME_CONTROLS:
                self.assertIn("action %s ok" % control, result.stdout.splitlines())


class ChainTests(unittest.TestCase):
    """from the game controls to what the unit is told"""

    def test_game_controls_are_player_controls_buttons(self):
        abstraction = re.search(r"enum\n\{\n(\t_game_control_jump,.*?)\tNUMBER_OF_GAME_CONTROLS", _text(INPUT_ABSTRACTION),
                                re.S).group(1)
        player = re.search(r"enum control_button\n\{\n(.*?)\tNUMBER_OF_ACTION_CONTROL_BUTTONS", _text(PLAYER_CONTROL),
                           re.S).group(1)
        controls = re.findall(r"_game_control_(\w+)", abstraction)
        buttons = re.findall(r"_button_(\w+)", player)
        self.assertEqual(controls, list(GAME_CONTROLS))
        self.assertEqual(buttons, ["jump", "switch_grenade", "action_reload", "switch_weapon", "melee_attack",
                                   "flashlight", "throw_grenade", "fire", "start", "back", "crouch", "scope_zoom"])
        # input_abstraction_update hands each game control the layout's button, index for index
        self.assertIn("state->buttons[control_index] =\n\t\t\t\t\tgamepad->buttons[input_abstraction_globals."
                      "player_control_preferences[controller_index].game_control_to_xbox_buttons[control_index]];",
                      _text(INPUT_ABSTRACTION))

    def test_buttons_reach_the_unit(self):
        text = _text(PLAYER_CONTROL)
        compact = re.sub(r"\s+", " ", text)
        for flag, button, edge in (
                ("_unit_control_crouch_modifier_bit", "crouch", ""),
                ("_unit_control_weapon_primary_trigger_bit", "fire", ""),
                ("_unit_control_throw_grenade_bit", "throw_grenade", ""),
                ("_unit_control_weapon_secondary_trigger_bit", "throw_grenade", ""),
                ("_player_control_input_zoom_bit", "scope_zoom", " == TRUE"),
                ("_unit_control_action_bit", "action_reload", ""),
                ("_unit_control_integrated_light_bit", "flashlight", ""),
                ("_unit_control_jump_bit", "jump", ""),
                ("_unit_control_use_equipment_bit", "melee_attack", ""),
                ("_player_control_rotate_weapons_bit", "switch_weapon", " == TRUE"),
                ("_player_control_rotate_grenades_bit", "switch_grenade", " == TRUE")):
            self.assertIn("%s, effective_buttons[_button_%s]%s);" % (flag, button, edge), compact, flag)
        # reload and the weapon swap are X's press and hold, by the held count
        self.assertIn("_unit_control_swap_weapons_bit, effective_buttons[_button_action_reload] >= "
                      "constants->minimum_weapon_swap_ticks);", compact)

    def test_look_inversion_is_the_engines(self):
        body = _function(_text(INPUT_ABSTRACTION), "input_abstraction_update")
        self.assertEqual(body.count("state->pitch = (invert_look ? -1.f : 1.f) * right_stick.y;"), 2)
        self.assertEqual(body.count("state->pitch = (invert_look ? -1.f : 1.f) * left_stick.y;"), 2)
        self.assertIn("invert_look = local_player_is_piloting_aircraft((short)controller_index);", body)

    def test_dead_zone_is_applied_to_every_axis(self):
        body = _function(_text(INPUT_XBOX), "input_get_device_states")
        self.assertEqual(body.count("GAMEPAD_STICK_DEAD_RANGE);"), 4)
        self.assertIn("GAMEPAD_STICK_DEAD_RANGE = 9000,", _text(INPUT_XBOX))

    def test_unplugging_lets_go(self):
        body = _function(_text(INPUT_XBOX), "input_get_device_states")
        removal = _between(body, "if (TEST_FLAG(removals, gamepad_index))", "if (TEST_FLAG(insertions, gamepad_index))")
        self.assertIn("&input_globals.gamepad_states[gamepad_index],", removal)
        self.assertLess(removal.index("= NULL;"), removal.index("csmemset("))


class LayerSignalTests(unittest.TestCase):
    def test_the_menus_say_whether_they_are_up(self):
        widget = _text(ROOT / "source" / "interface" / "ui_widget.c")
        self.assertIn("halo_ui_pointer_update(ui_mouse_menus_active(), &pointer)", widget)
        self.assertIn("ui_widgets_process_mouse();", _function(widget, "process_ui_widgets"))
        main = _text(ROOT / "source" / "main" / "main.c")
        # read first, then the menus: the layer a frame's menus pick is the next frame's
        self.assertLess(main.index("\t\tinput_frame_begin();\n\t\tinput_update();\n\t\tinput_abstraction_update();"),
                        main.index("\t\t\tprocess_ui_widgets();"))

    def test_the_hook_is_the_bridges(self):
        self.assertIn("int halo_ui_pointer_update(", _text(WII_XINPUT))
        unsupported = _text(UNSUPPORTED_PORT)
        self.assertNotIn('wii_unsupported("input", "halo_ui_pointer_update")', unsupported)
        # the keyboard's actions stay the desktop's: the pad's are the controller's own buttons
        self.assertIn('wii_unsupported("input", "halo_keyboard_actions")', unsupported)

    def test_menu_layer_is_hwi_016d(self):
        table = _between(_text(WII_XINPUT), "menu_bindings[] =", "};")
        for pad, xbox in (("A", "0, XINPUT_GAMEPAD_A"), ("B", "0, XINPUT_GAMEPAD_B"), ("X", "0, XINPUT_GAMEPAD_X"),
                          ("Y", "0, XINPUT_GAMEPAD_Y"), ("START", "XINPUT_GAMEPAD_START,"),
                          ("Z", "XINPUT_GAMEPAD_BACK,"), ("UP", "XINPUT_GAMEPAD_DPAD_UP,"),
                          ("DOWN", "XINPUT_GAMEPAD_DPAD_DOWN,"), ("LEFT", "XINPUT_GAMEPAD_DPAD_LEFT,"),
                          ("RIGHT", "XINPUT_GAMEPAD_DPAD_RIGHT,")):
            self.assertIn("{ WII_PAD_%s, %s" % (pad, xbox), table)


if __name__ == "__main__":
    unittest.main()
